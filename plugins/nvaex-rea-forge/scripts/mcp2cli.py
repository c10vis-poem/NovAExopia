#!/usr/bin/env python3
"""MCP stdio server -> token-light CLI shim + SKILL.md (from mcp2cli; stdlib only, no MCP SDK).
  mcp2cli.py tools <server cmd...>                      print tools/list JSON
  mcp2cli.py call  <server cmd...> -- <tool> [k=v ...]  one tools/call; values parse as JSON else string
  mcp2cli.py gen   <name> <outdir> <server cmd...>      write <outdir>/<name> (sh shim) and <outdir>/SKILL.md
The server is started per call and exits when stdin closes; nothing stays running."""
import json, os, shlex, stat, subprocess, sys

def session(cmd, reqs, timeout=60):
    p = subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
    def send(m): p.stdin.write(json.dumps(m) + "\n"); p.stdin.flush()
    def recv(i):
        while True:
            l = p.stdout.readline()
            if not l: sys.exit("server closed before answering")
            m = json.loads(l)
            if m.get("id") == i: return m
    try:
        send({"jsonrpc": "2.0", "id": 0, "method": "initialize", "params": {
            "protocolVersion": "2024-11-05", "capabilities": {}, "clientInfo": {"name": "mcp2cli", "version": "0.1"}}})
        recv(0); send({"jsonrpc": "2.0", "method": "notifications/initialized"})
        out = []
        for i, (method, params) in enumerate(reqs, 1):
            send({"jsonrpc": "2.0", "id": i, "method": method, "params": params}); out.append(recv(i))
        return out
    finally:
        p.stdin.close()
        try: p.wait(timeout)
        except subprocess.TimeoutExpired: p.kill()

def tools(cmd):
    r = session(cmd, [("tools/list", {})])[0]
    if "error" in r: sys.exit(json.dumps(r["error"]))
    return r["result"]["tools"]

def val(s):
    try: return json.loads(s)
    except ValueError: return s

def call(cmd, tool, kv):
    args = dict(a.split("=", 1) for a in kv)
    r = session(cmd, [("tools/call", {"name": tool, "arguments": {k: val(v) for k, v in args.items()}})])[0]
    if "error" in r: sys.exit(json.dumps(r["error"]))
    res = r["result"]
    print("\n".join(c.get("text", json.dumps(c)) for c in res.get("content", [])))
    sys.exit(1 if res.get("isError") else 0)

def gen(name, out, cmd):
    ts = tools(cmd); os.makedirs(out, exist_ok=True)
    me = os.path.abspath(__file__)
    shim = os.path.join(out, name)
    open(shim, "w").write(f'#!/usr/bin/env sh\n# generated by mcp2cli\nexec python3 {shlex.quote(me)} call {" ".join(map(shlex.quote, cmd))} -- "$@"\n')
    os.chmod(shim, os.stat(shim).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    L = [f"---\nname: {name}\ndescription: Command line for {len(ts)} tools: " + ", ".join(t["name"] for t in ts) + f". Use when you need any of them; run `{name} <tool> key=value ...`.\n---\n"]
    for t in ts:
        props = t.get("inputSchema", {}).get("properties", {}); req = set(t.get("inputSchema", {}).get("required", []))
        ps = " ".join(f"{k}=<{v.get('type', 'value')}>" + ("" if k in req else "?") for k, v in props.items())
        L.append(f"- `{name} {t['name']} {ps}`: {t.get('description', '').splitlines()[0] if t.get('description') else ''}")
    L.append("\nValues parse as JSON, else string. `?` marks optional. Output is the tool text; exit 1 if the tool errored.")
    open(os.path.join(out, "SKILL.md"), "w").write("\n".join(L) + "\n")
    print(shim)

a = sys.argv[1:]
if a[:1] == ["tools"] and len(a) > 1: print(json.dumps(tools(a[1:]), indent=1))
elif a[:1] == ["call"] and "--" in a:
    i = a.index("--"); call(a[1:i], a[i + 1], a[i + 2:])
elif a[:1] == ["gen"] and len(a) > 4: gen(a[1], a[2], a[3:])
else: sys.exit(__doc__)
