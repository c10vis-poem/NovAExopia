#!/usr/bin/env python3
"""Wrap one CLI entrypoint of a harvested card as a shell shim + thin SKILL.md (for MCP servers use mcp2cli.py).
usage: wrap.py <CAPABILITY_CARD.json> [--index N] [--bin-dir DIR]
Writes into <card dir>/wrap/ by default; --bin-dir installs the shim there (e.g. ~/.local/bin)."""
import argparse, json, os, stat, sys

ap = argparse.ArgumentParser()
ap.add_argument("card"); ap.add_argument("--index", type=int, default=0); ap.add_argument("--bin-dir")
a = ap.parse_args()
c = json.load(open(a.card))
if not c["entrypoints"]:
    sys.exit("no entrypoints in card; use the skill gate instead")
e = c["entrypoints"][a.index]
name = (e["cmd"].split()[-1] if e["kind"] in ("npm-bin", "py-script") else c["name"]).replace("/", "-")
d = os.path.join(os.path.dirname(os.path.abspath(a.card)), "wrap")
os.makedirs(d, exist_ok=True)
run = {"npm-bin": f'node "{c["source"]}/{e["file"]}"', "py-script": f'python3 -m {e["file"].split(":")[0]}',
       "go-main": f'(cd "{c["source"]}" && go run .)'}.get(e["kind"], e["cmd"].replace("python ", "python3 ").replace(e["file"], f'"{c["source"]}/{e["file"]}"'))
shim = os.path.join(d, name)
open(shim, "w").write(f'#!/usr/bin/env sh\n# generated by nvaex-rea-forge from {c["id"]}\nexec {run} "$@"\n')
os.chmod(shim, os.stat(shim).st_mode | stat.S_IXUSR | stat.S_IXGRP)
if a.bin_dir:
    os.makedirs(a.bin_dir, exist_ok=True)
    t = os.path.join(a.bin_dir, name)
    open(t, "w").write(open(shim).read()); os.chmod(t, 0o755)
open(os.path.join(d, "SKILL.md"), "w").write(
    f"---\nname: {name}\ndescription: Run the {name} CLI harvested from {c['name']}. Use when its capability is needed; call `{name} --help` first.\n---\n\n"
    f"`{name}` wraps `{e['file']}` ({e['kind']}) from `{c['source']}`.\nRun `{name} --help`, then call it with Bash. Card: `{c['id']}`.\n")
print(shim)
